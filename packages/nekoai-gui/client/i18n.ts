const dicts: Record<Locale, Record<string, string>> = {
  'en-US': enUS,
  'zh-CN': zhCN,
}

export type MessageKey = keyof typeof enUS

export function t(key: string, params?: Record<string, string | number>) {
  const table = dicts[currentLocale.value] || dicts['en-US']
  let text = table[key] ?? dicts['en-US'][key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

export function formatProgress(message?: string, fallback = '') {
  if (!message) return fallback
  const [key, arg] = message.split(':')
  const translated = t(key, arg ? { arg } : undefined)
  return translated === key ? message : translated
}
